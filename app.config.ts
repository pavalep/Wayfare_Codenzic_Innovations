import type {ConfigContext, ExpoConfig} from 'expo/config';
import {
  AndroidConfig,
  withAndroidColors,
  withAndroidManifest,
  withDangerousMod,
  type ConfigPlugin,
} from 'expo/config-plugins';
import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';

/**
 * The dynamic app config.
 *
 * WHY A `app.config.ts` AND NOT AN `app.json`
 *
 * `app.json` is static JSON — it cannot read an environment variable.
 * The Google Maps API key has to come from the environment, because a
 * key committed to the repository is a key that ends up in somebody
 * else's APK. `app.config.ts` is the same config written in
 * TypeScript, evaluated at build time, and it can read `process.env`.
 *
 * The static half still lives in `app.json`; this file receives it as
 * `config` and layers the dynamic parts on top. That keeps the
 * difference between "what the app is" and "what the build needs"
 * visible.
 *
 * NOTE FOR AN RN-CLI READER
 *
 * A bare React Native app has no config plugin system at all —
 * native project edits are made by hand in `android/` and `ios/`.
 * Expo's config plugins are the replacement for that: a plugin
 * receives the config, mutates the native projects during
 * `expo prebuild`, and the generated `android/` folder is disposable
 * (it is regenerated, never edited by hand).
 */

/**
 * The Google Maps SDK key for Android.
 *
 * Read from `.env` (Expo loads `.env` files automatically for
 * `EXPO_PUBLIC_*` and `NODE_ENV` variables). The key is restricted in
 * the Google Cloud console to this app's package name and SHA-1, and
 * it is NEVER committed — `.env` is in `.gitignore`.
 */
const googleMapsApiKey = process.env.EXPO_PUBLIC_GOOGLE_MAPS_API_KEY ?? '';

/**
 * The brand orange.
 *
 * The same value as `palette.brand` in `src/theme/tokens.ts`. It is
 * repeated here because the config plugin cannot import from the app's
 * source tree — the config is evaluated before the app is built, and
 * it has to be plain data.
 */
const BRAND_ORANGE = '#F1521F';

/**
 * Puts the brand colour into the NATIVE theme.
 *
 * The Android template ships a dark blue as `colorPrimary`, and the
 * native theme hands that colour to things React Native does not
 * draw: the text cursor, the default ripple, the system dialogs.
 * Leaving the blue there means the app's own controls are orange and
 * the system's are blue, which is the kind of seam that reads as
 * "unfinished" without anybody being able to say why.
 *
 * This is a config plugin rather than a hand-edited `colors.xml`
 * because `android/` is regenerated by every `expo prebuild` — an
 * edit made there does not survive. See the note about config
 * plugins above.
 */
const withBrandNativeColors: ConfigPlugin = config =>
  withAndroidColors(config, androidConfig => {
    androidConfig.modResults = AndroidConfig.Colors.assignColorValue(
      androidConfig.modResults,
      {name: 'colorPrimary', value: BRAND_ORANGE},
    );
    return androidConfig;
  });

/**
 * The release signing key.
 *
 * Everything about it comes from the environment, because everything
 * about it is secret. `.env` holds the path, the alias and the two
 * passwords; `.env` is git-ignored.
 *
 * WHEN THESE ARE ABSENT
 *
 * The plugin still writes the release signing block — it just points
 * at nothing. A release build then fails at the signing step with a
 * message about the missing password, which is the correct outcome:
 * a release APK that silently fell back to the debug key would have a
 * different fingerprint from the one the Maps key is restricted to,
 * and that shows up much later as a blank map on somebody's phone.
 * A DEBUG build is unaffected either way.
 */
const keystorePath = process.env.WAYFARE_KEYSTORE_PATH ?? '';
const keystorePassword = process.env.WAYFARE_KEYSTORE_PASSWORD ?? '';
const keyAlias = process.env.WAYFARE_KEY_ALIAS ?? '';

/**
 * Signs the release build with the release key.
 *
 * WHY A CONFIG PLUGIN
 *
 * `android/` is generated. `expo prebuild` deletes it and writes it
 * again from the template, so a hand-edited `build.gradle` does not
 * survive the next prebuild.
 *
 * WHY THE BLOCK HOLDS NO SECRETS
 *
 * The `android/` project is committed, so its `build.gradle` is a
 * file everybody can read. It therefore names the signing values
 * rather than containing them: the path, the alias and the two
 * passwords are read from the environment at build time, and
 * `scripts/build-android.mjs` puts them there from `.env`.
 *
 * The consequence is that the committed project carries no password
 * and the keystore itself stays outside the repository — which is
 * exactly where a private key belongs.
 */
const withReleaseSigning: ConfigPlugin = config => {
  if (!keystorePath && !keystorePassword && !keyAlias) {
    return config;
  }

  return withDangerousMod(config, [
    'android',
    async androidConfig => {
      const appDir = path.join(
        androidConfig.modRequest.projectRoot,
        'android',
        'app',
      );
      const buildGradlePath = path.join(appDir, 'build.gradle');

      /**
       * The path Gradle sees.
       *
       * The build script exports an ABSOLUTE path, because Gradle
       * resolves a relative one against `android/app/` and the value
       * in `.env` is relative to the project root. The relative
       * default is the layout this repository uses.
       */
      const relativeKeystore = path
        .relative(appDir, path.join(androidConfig.modRequest.projectRoot, 'keystores'))
        .split(path.sep)
        .join('/');

      let contents = await readFile(buildGradlePath, 'utf8');

      /**
       * Point the release build type at the release signing config.
       *
       * The template signs `release` with the DEBUG key. That is fine
       * for a throwaway build and wrong for anything a reviewer
       * installs, because the Maps key is restricted by fingerprint.
       */
      contents = contents.replace(
        /(release\s*\{[^}]*?)signingConfig signingConfigs\.debug/,
        '$1signingConfig signingConfigs.release',
      );

      /**
       * Add the release signing config itself.
       *
       * Nothing secret is written here — only the NAMES of the
       * places the values come from.
       */
      contents = contents.replace(
        /(signingConfigs\s*\{)/,
        `$1
        release {
            storeFile file(findProperty('wayfareKeystore') ?: System.getenv('WAYFARE_KEYSTORE_PATH') ?: '${relativeKeystore}/wayfare-release.keystore')
            storePassword System.getenv('WAYFARE_KEYSTORE_PASSWORD') ?: findProperty('wayfareKeystorePassword')
            keyAlias System.getenv('WAYFARE_KEY_ALIAS') ?: findProperty('wayfareKeystoreAlias') ?: '${keyAlias || 'wayfare-release'}'
            keyPassword System.getenv('WAYFARE_KEY_PASSWORD') ?: findProperty('wayfareKeyPassword')
        }`,
      );

      await writeFile(buildGradlePath, contents, 'utf8');

      return androidConfig;
    },
  ]);
};

/**
 * Writes the Maps key into a git-ignored resource file.
 *
 * WHY NOT STRAIGHT INTO THE MANIFEST
 *
 * The `android/` project is committed, so a key written into
 * `AndroidManifest.xml` is a key in the repository. That is the one
 * thing this whole arrangement exists to prevent: the key is
 * restricted to a package name and a signing fingerprint, but a
 * repository is public, and the fingerprint restriction is the only
 * thing between the key and anybody else's phone.
 *
 * So the manifest refers to the value BY NAME —
 * `@string/google_maps_key` — and the value itself lives in
 * `android/app/src/main/res/values/key.xml`, which is generated on
 * every prebuild and git-ignored.
 *
 * The file is generated rather than hand-written because
 * `expo prebuild` deletes `android/` and writes it again: a
 * hand-written `key.xml` would not survive the next prebuild, and a
 * missing one is a build error ("resource string/google_maps_key not
 * found"), not a warning.
 *
 * The name of the resource is a constant, and the manifest is
 * committed with it, so the two cannot drift apart.
 */
const withGoogleMapsKeyResource: ConfigPlugin = config => {
  /**
   * Point the manifest at the resource.
   *
   * `addMetaDataItemToMainApplication` adds the entry if it is
   * missing and replaces the value if it is not — which is what makes
   * this plugin the single owner of the entry, whichever plugin
   * touched it before.
   */
  const withManifest = withAndroidManifest(config, androidConfig => {
    const mainApplication = AndroidConfig.Manifest.getMainApplicationOrThrow(
      androidConfig.modResults,
    );

    AndroidConfig.Manifest.addMetaDataItemToMainApplication(
      mainApplication,
      'com.google.android.geo.API_KEY',
      '@string/google_maps_key',
    );

    return androidConfig;
  });

  /**
   * Write the resource file itself.
   */
  return withDangerousMod(withManifest, [
    'android',
    async androidConfig => {
      const valuesDir = path.join(
        androidConfig.modRequest.projectRoot,
        'android',
        'app',
        'src',
        'main',
        'res',
        'values',
      );

      const contents = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!--',
        '     The Google Maps SDK key.',
        '',
        '     THIS FILE IS NOT COMMITTED. It holds a secret.',
        '',
        '     It is written by `expo prebuild` from the',
        '     EXPO_PUBLIC_GOOGLE_MAPS_API_KEY environment variable, and the',
        '     AndroidManifest refers to the value by name rather than',
        '     carrying it literally — so the committed manifest holds no key.',
        '-->',
        '<resources>',
        `    <string name="google_maps_key" translatable="false">${googleMapsApiKey}</string>`,
        '</resources>',
        '',
      ].join('\n');

      await writeFile(path.join(valuesDir, 'key.xml'), contents, 'utf8');

      return androidConfig;
    },
  ]);
};

/**
 * The ProGuard rules the release build needs.
 *
 * They are written into `android/app/proguard-rules.pro` rather than
 * edited there by hand, because `expo prebuild` rewrites that file
 * from the template and a hand-edit does not survive it. The same
 * reason the signing block is written by a plugin.
 *
 * WHY THE RELEASE BUILD NEEDS THEM
 *
 * `react-native-maps` pulls in `androidx.work:work-runtime` for its
 * tile cache, and WorkManager builds a Room database the moment the
 * app starts — androidx.startup's `InitializationProvider` runs
 * `WorkManagerInitializer` before the first Activity.
 *
 * Room instantiates that database by NAME, so R8 cannot see the
 * reference and removes the generated implementation. The release
 * build then dies on launch, before it draws anything, with:
 *
 *   Failed to create an instance of class
 *   androidx.work.impl.WorkDatabase
 *
 * WorkManager's own consumer rules keep the Worker classes but not the
 * database, so these are added here.
 *
 * `-keep class * extends androidx.room.RoomDatabase` is the rule that
 * matters: it keeps the NAME of the generated implementation, which is
 * what Room looks up by string.
 */
const PROGUARD_RULES = `
# --- WorkManager's database -----------------------------------------
#
# react-native-maps pulls in androidx.work:work-runtime for its tile
# cache, and WorkManager builds a Room database the moment the app
# starts. Room instantiates it by name, so R8 cannot see the reference
# and removes the generated class — the release build then dies on
# launch with "Failed to create an instance of class
# androidx.work.impl.WorkDatabase".
#
# WorkManager's own consumer rules keep the Worker classes but not the
# database, so the keeps are added here.
-keep class androidx.work.impl.** { *; }
-keep class androidx.work.impl.WorkDatabase_Impl { *; }
-keep class * extends androidx.room.RoomDatabase { <init>(); }
-keepclassmembers class * extends androidx.room.RoomDatabase { <init>(); }
-dontwarn androidx.room.paging.**
-dontwarn androidx.work.**
`;

/**
 * Marker used to tell whether the rules have already been written.
 */
const PROGUARD_MARKER = '# --- WorkManager\'s database ---';

const withProguardRules: ConfigPlugin = config =>
  withDangerousMod(config, [
    'android',
    async androidConfig => {
      const proguardPath = path.join(
        androidConfig.modRequest.projectRoot,
        'android',
        'app',
        'proguard-rules.pro',
      );

      let contents = await readFile(proguardPath, 'utf8');

      if (!contents.includes(PROGUARD_MARKER)) {
        await writeFile(proguardPath, `${contents}\n${PROGUARD_RULES}`, 'utf8');
      }

      return androidConfig;
    },
  ]);

export default ({config}: ConfigContext): ExpoConfig => ({
  ...config,
  name: 'Wayfare',
  slug: 'wayfare',
  scheme: 'wayfare',
  orientation: 'portrait',
  userInterfaceStyle: 'light',
  ios: {
    ...config.ios,
    bundleIdentifier: 'com.codenzic.wayfare',
    config: {
      googleMapsApiKey,
    },
  },
  android: {
    ...config.android,
    package: 'com.codenzic.wayfare',
    /**
     * The Maps key is NOT set here.
     *
     * `android.config.googleMaps.apiKey` writes the key straight into
     * `AndroidManifest.xml`, and the `android/` project is committed.
     * `withGoogleMapsKeyResource` puts it in a git-ignored resource
     * file instead, and the manifest refers to it by name.
     */
    // "Use current location" needs fine + coarse location.
    permissions: [
      'ACCESS_COARSE_LOCATION',
      'ACCESS_FINE_LOCATION',
    ],
  },
  plugins: [
    /**
     * The Maps key resource.
     *
     * IT GOES FIRST ON PURPOSE.
     *
     * Expo runs a mod in the REVERSE of the order the plugins are
     * registered: each plugin's action runs first and then hands the
     * result to the plugin registered before it. Registering this one
     * first therefore makes it run LAST — which is what it needs,
     * because it owns the manifest's Maps meta-data and has to have
     * the last word on it.
     */
    withGoogleMapsKeyResource,

    // The Expo Router plugin registers the deep-link scheme and the
    // `expo-router/entry` bootstrap.
    'expo-router',
    [
      'react-native-maps',
      {
        /**
         * The Android key is deliberately NOT passed here.
         *
         * Passing it would write it straight into the committed
         * `AndroidManifest.xml`. `withGoogleMapsKeyResource` below
         * owns the Android meta-data instead, and points the manifest
         * at a resource whose value lives in a git-ignored file.
         *
         * The iOS key is still passed: `ios/` is not committed, and
         * the iOS build needs it in `Info.plist`.
         */
        iosGoogleMapsApiKey: googleMapsApiKey,
      },
    ],
    [
      'expo-location',
      {
        locationWhenInUsePermission:
          'Wayfare uses your location to set the start of your trip.',
      },
    ],
    /**
     * The splash screen.
     *
     * The screen is the brand orange with the white route glyph on
     * it — the same artwork as the launcher icon, so the app opens
     * with the mark it is installed as.
     *
     * `imageWidth` is how wide the mark is drawn, in dp. The default
     * is 100, which is a little small for a mark this simple; 140
     * puts the glyph at a size that reads as a splash screen rather
     * than as a detail on one.
     */
    [
      'expo-splash-screen',
      {
        image: './assets/splash-icon.png',
        imageWidth: 140,
        resizeMode: 'contain',
        backgroundColor: BRAND_ORANGE,
        dark: {
          backgroundColor: BRAND_ORANGE,
        },
      },
    ],
    withBrandNativeColors,
    withReleaseSigning,
    withProguardRules,
  ] as unknown as ExpoConfig['plugins'],
  experiments: {
    ...config.experiments,
    typedRoutes: true,
  },
  extra: {
    // Exposed to the app through `expo-constants`. Useful for
    // checking at runtime whether the build was made with a Maps key.
    googleMapsApiKeyConfigured: Boolean(googleMapsApiKey),
  },
});
