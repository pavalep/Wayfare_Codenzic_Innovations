#!/usr/bin/env node
/**
 * Builds the Android APK for Wayfare.
 *
 * WHY A SCRIPT AND NOT AN NPM SCRIPT
 *
 * `expo prebuild` generates the `android/` project, and the APK is
 * then produced by Gradle. The two steps have to run in order, and the
 * Gradle wrapper is `gradlew.bat` on Windows but `./gradlew` everywhere
 * else. Spelling that out in a cross-platform npm script is possible
 * but ugly, so it lives here instead and the npm scripts just call
 * this file.
 *
 * USAGE
 *
 *   npm run build:apk              debug APK
 *   npm run build:apk -- --release release APK
 *   npm run build:apk -- --no-prebuild   reuse the existing android/
 *
 * The Google Maps API key is read from `.env` by `app.config.ts`
 * DURING the prebuild step, so `.env` must exist before this script
 * runs if you want the map to render real tiles. Without a key the
 * app still builds and installs; the map area simply shows Google's
 * grey authorisation-failure canvas instead of tiles.
 *
 * THE RELEASE KEY
 *
 * A release build is signed with the keystore named in `.env`. The
 * passwords are handed to Gradle through the ENVIRONMENT, because the
 * committed `android/` project names those values rather than
 * containing them — a keystore password must never end up in a file
 * everybody can read.
 */

import {spawnSync} from 'node:child_process';
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import {dirname, isAbsolute, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ANDROID_DIR = join(ROOT, 'android');
const ARTIFACTS_DIR = join(ROOT, 'artifacts');

const args = process.argv.slice(2);
const variant = args.includes('--release') ? 'release' : 'debug';
const skipPrebuild = args.includes('--no-prebuild');

/**
 * Reads `.env` into an object.
 *
 * A deliberately small parser: the file is a flat list of
 * `KEY=value` lines, and a dependency-free one keeps the build
 * script runnable in a bare checkout.
 */
function readEnvFile() {
  const envPath = join(ROOT, '.env');

  if (!existsSync(envPath)) {
    return {};
  }

  const values = {};

  for (const line of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();

    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }

    const separator = trimmed.indexOf('=');

    if (separator === -1) {
      continue;
    }

    values[trimmed.slice(0, separator).trim()] = trimmed
      .slice(separator + 1)
      .trim()
      .replace(/^["']|["']$/g, '');
  }

  return values;
}

/**
 * The signing values, ready for Gradle.
 *
 * The keystore path is resolved to an ABSOLUTE one: the value in
 * `.env` is relative to the project root, and Gradle resolves a
 * relative path against `android/app/`.
 */
function signingEnvironment() {
  const env = readEnvFile();
  const signing = {};

  if (env.WAYFARE_KEYSTORE_PATH) {
    signing.WAYFARE_KEYSTORE_PATH = isAbsolute(env.WAYFARE_KEYSTORE_PATH)
      ? env.WAYFARE_KEYSTORE_PATH
      : join(ROOT, env.WAYFARE_KEYSTORE_PATH);
  }

  for (const key of [
    'WAYFARE_KEYSTORE_PASSWORD',
    'WAYFARE_KEY_ALIAS',
    'WAYFARE_KEY_PASSWORD',
  ]) {
    if (env[key]) {
      signing[key] = env[key];
    }
  }

  return signing;
}

/**
 * Puts back the two machine-specific settings a prebuild wipes.
 *
 * `expo prebuild` deletes `android/` and writes it again, which takes
 * `local.properties` — the path to this machine's Android SDK — and
 * the local JVM settings in `gradle.properties` with it.
 *
 * Neither is committed, on purpose: they describe one machine rather
 * than the project. So the build puts them back.
 */
function restoreLocalMachineSettings() {
  const sdkDir = process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT;

  if (!sdkDir) {
    console.warn(
      '\nANDROID_HOME is not set — skipping local.properties. Gradle may ' +
        'not find the Android SDK.\n',
    );
    return;
  }

  /**
   * The SDK's CMake folder, if it has one.
   */
  const cmakeDir = join(sdkDir, 'cmake');
  const cmakeVersions = existsSync(cmakeDir)
    ? ['3.31.6', '3.22.1']
        .map(version => join(cmakeDir, version))
        .filter(candidate => existsSync(candidate))
    : [];

  const properties = [
    '## This file is automatically generated by Android Studio.',
    '##',
    '## Do not modify this file -- YOUR CHANGES WILL BE ERASED!',
    '##',
    '## This file must be checked into Version Control Systems (i.e., Git)',
    '## as it is essential to automatically regenerate the project configuration.',
    '##',
    '## Location of the SDK. This is only used by Gradle.',
    `sdk.dir=${sdkDir.replace(/\\/g, '\\\\')}`,
  ];

  if (cmakeVersions.length > 0) {
    properties.push(
      '',
      '## Location of the CMake that the Android SDK ships with.',
      `cmake.dir=${cmakeVersions[0].replace(/\\/g, '\\\\')}`,
    );
  }

  writeFileSync(join(ANDROID_DIR, 'local.properties'), `${properties.join('\n')}\n`);

  /**
   * The JVM settings.
   */
  const gradlePropertiesPath = join(ANDROID_DIR, 'gradle.properties');
  const gradleProperties = readFileSync(gradlePropertiesPath, 'utf8');

  if (!gradleProperties.includes('org.gradle.java.installations.auto-download')) {
    const jdk = join(
      process.env.PROGRAMFILES ?? 'C:\\Program Files',
      'Android',
      'Android Studio',
      'jbr',
    );

    writeFileSync(
      gradlePropertiesPath,
      `${gradleProperties}\n` +
        '# --- Toolchain settings ----------------------------------------------\n' +
        '#\n' +
        '# The Android build compiles the native code with a Java 21 toolchain.\n' +
        '# These two settings point Gradle at a JDK that is already installed\n' +
        '# rather than letting it try to download one, which fails on a machine\n' +
        '# with no access to the download service:\n' +
        '#\n' +
        '#   auto-download=false  stops Gradle fetching a JDK.\n' +
        '#   paths=...             the JDK 21 that ships with Android Studio.\n' +
        '#\n' +
        '# Gradle falls back to JAVA_HOME when that path does not exist, so this\n' +
        '# is harmless on a machine without Android Studio.\n' +
        'org.gradle.java.installations.auto-download=false\n' +
        `org.gradle.java.installations.paths=${jdk.replace(/\\/g, '\\\\')}\n`,
    );
  }
}

/**
 * Makes sure the Maps key resource exists.
 *
 * The prebuild writes it, but the build can be asked to reuse an
 * existing `android/` (`--no-prebuild`), and a missing `key.xml` is a
 * BUILD ERROR rather than a warning: the committed manifest refers to
 * `@string/google_maps_key`, so the resource has to be there for the
 * manifest to compile.
 *
 * The file is written from `.env`, exactly as the prebuild writes it.
 * An empty key is a valid value — the app falls back to the flat map
 * when the build carries no key.
 */
function restoreMapsKeyResource() {
  const keyXmlPath = join(
    ANDROID_DIR,
    'app',
    'src',
    'main',
    'res',
    'values',
    'key.xml',
  );

  if (existsSync(keyXmlPath)) {
    return;
  }

  const env = readEnvFile();

  writeFileSync(
    keyXmlPath,
    [
      '<?xml version="1.0" encoding="utf-8"?>',
      '<resources>',
      `    <string name="google_maps_key" translatable="false">${env.EXPO_PUBLIC_GOOGLE_MAPS_API_KEY ?? ''}</string>`,
      '</resources>',
      '',
    ].join('\n'),
  );

  console.log('\nWrote the Maps key resource (it was missing).');
}

/**
 * Runs a command and exits the process if it fails, so the first
 * broken step never silently produces a half-built APK.
 */
function run(command, commandArgs, cwd, extraEnv) {
  console.log(`\n> ${command} ${commandArgs.join(' ')}\n`);

  const result = spawnSync(command, commandArgs, {
    cwd,
    stdio: 'inherit',
    shell: process.platform === 'win32',
    env: {...process.env, ...(extraEnv ?? {})},
  });

  if (result.error) {
    console.error(`\nFailed to run "${command}":`, result.error.message);
    process.exit(1);
  }

  if (result.status !== 0) {
    console.error(`\n"${command}" exited with code ${result.status}.`);
    process.exit(result.status ?? 1);
  }
}

// ── Step 1 — generate (or refresh) the native Android project ──

if (!skipPrebuild) {
  run('npx', ['expo', 'prebuild', '--platform', 'android', '--no-install'], ROOT);
} else if (!existsSync(ANDROID_DIR)) {
  console.error(
    '\n--no-prebuild was passed but there is no android/ directory. ' +
      'Run the prebuild step first.\n',
  );
  process.exit(1);
}

// ── Step 2 — hand the project to Gradle ──

restoreLocalMachineSettings();
restoreMapsKeyResource();

const gradlew = process.platform === 'win32' ? 'gradlew.bat' : './gradlew';
const gradleTask = variant === 'release' ? 'assembleRelease' : 'assembleDebug';

run(gradlew, [gradleTask, '--console=plain'], ANDROID_DIR, signingEnvironment());

// ── Step 3 — find the APK and copy it somewhere obvious ──

const apkDir = join(ANDROID_DIR, 'app', 'build', 'outputs', 'apk', variant);
const apkPath = join(apkDir, `app-${variant}.apk`);

if (!existsSync(apkPath)) {
  console.error(`\nGradle reported success but ${apkPath} does not exist.`);
  console.error(`Look in ${apkDir} for the APK.`);
  process.exit(1);
}

if (!existsSync(ARTIFACTS_DIR)) {
  mkdirSync(ARTIFACTS_DIR, {recursive: true});
}

const artifact = join(ARTIFACTS_DIR, `wayfare-${variant}.apk`);
copyFileSync(apkPath, artifact);

console.log(`\nAPK ready:\n  ${artifact}\n`);
console.log(
  'Install it with:\n' +
    '  adb install -r "' +
    artifact +
    '"\n',
);
